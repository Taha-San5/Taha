export function Icon({
  name,
  className,
  size = 16,
  strokeWidth = 1.75,
}: {
  name: string;
  className?: string;
  size?: number;
  strokeWidth?: number;
}) {
  const Component = ICONS[name] ?? CircleDot;
  return <Component className={className} size={size} strokeWidth={strokeWidth} aria-hidden />;
}
